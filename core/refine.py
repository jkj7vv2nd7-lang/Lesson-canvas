"""
生成済みの成果物を、別のAI（プロバイダー/モデル）に批評・推敲させて
品質を底上げする「ブラッシュアップ」機能。

市販の指導案作成ソフトの多くは1つのテンプレートエンジンで完結しているが、
ここでは「複数の高性能AIによる相互チェック」という強みを活かし、
- 新学習指導要領の観点との整合性
- 発問・評価規準の具体性
- 表現の学年適合性
などを別モデルの視点でレビューし、改善版を作る。
"""

from __future__ import annotations

CRITIQUE_AND_REFINE_PROMPT_TEMPLATE = """
あなたは日本の学校教育・教育評価に精通した、非常に厳しい指導主事です。
以下の「{label}」の下書きを、次の観点で厳しくレビューし、改善したうえで
**改善後の全文のみ**を出力してください（レビューコメント自体は出力しない）。

【レビュー観点】
1. 新学習指導要領の3観点（知識・技能／思考・判断・表現／主体的に学習に取り組む態度）との整合性
2. 評価規準・評価方法の具体性（曖昧な表現がないか）
3. 発問や指示の具体性（実際の授業でそのまま使える表現か）
4. 対象学年の児童生徒にとって適切な語彙・難易度か
5. 表構造・Markdown記法が壊れていないか（元のフォーマットを保つこと）

【出力ルール】
- 元のMarkdown構造（見出し・表形式）は維持すること
- 表(|...|)の書式は厳密に保つこと（区切り行、セル内改行禁止など）
- 改善点の説明や前置きは一切書かず、改善後の本文のみを出力すること

--- 下書き ---
{draft_content}
--- ここまで ---
""".strip()


def build_refine_prompt(label: str, draft_content: str) -> str:
    return CRITIQUE_AND_REFINE_PROMPT_TEMPLATE.format(label=label, draft_content=draft_content)
